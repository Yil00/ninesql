//! Whether a table can be edited, and by which row key (F-DATA-04, I8).

use std::fmt;

use ninesql_driver_api::dml::{KeyCandidate, KeyKind, choose_row_key};
use ninesql_driver_api::metadata::{ObjectDetails, ObjectInfo, ObjectPath, TableInfo};
use ninesql_driver_api::{EngineId, ObjectKind};

/// A column of an edited table, from the metadata service ([`ninesql_driver_api::ColumnInfo`]).
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct TableColumn {
    /// Name, unquoted.
    pub name: String,
    /// Engine type name as the engine spells it.
    pub data_type: String,
    /// Accepts `NULL`.
    pub nullable: bool,
    /// Part of the primary key.
    pub primary_key: bool,
    /// Generated by the engine (identity, auto-increment, serial): left out of duplicated rows.
    pub auto_generated: bool,
    /// Has a default expression.
    pub has_default: bool,
}

/// The key rows are identified by in `UPDATE` / `DELETE`.
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct RowKey {
    /// Key columns, unquoted, in key order.
    pub columns: Vec<String>,
    /// Primary key or unique key ([`KeyKind`]).
    pub kind: KeyKind,
}

/// A table whose rows can be edited: its columns and row key. Build it with
/// [`EditService::describe_table`](super::EditService::describe_table) (from the metadata
/// service) or [`EditableTable::from_metadata`].
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct EditableTable {
    /// Navigator path of the table.
    pub path: ObjectPath,
    /// Name parts the DML uses (nearest schema, else catalog, then the table), unquoted.
    pub table: Vec<String>,
    /// Columns in ordinal order.
    pub columns: Vec<TableColumn>,
    /// The row key.
    pub key: RowKey,
    /// [`TableInfo::transactional`]: `Some(true)`, or `None` when the driver does not know.
    pub transactional: Option<bool>,
}

/// Why rows of a result cannot be edited. Shown to the user as the explanation of a read-only
/// grid (I8); never holds a value.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error)]
#[non_exhaustive]
pub enum NotEditable {
    /// The session is read-only (I3).
    #[error("the connection is read-only")]
    ReadOnlySession,
    /// The driver declares no row editing for this engine (I8).
    #[error("this engine does not support editing rows")]
    NotSupported,
    /// The driver has no transactions (auto-commit only): a failed save could not be undone.
    #[error("this engine has no transactions, so a save could not be undone if it failed")]
    NoTransactions,
    /// The driver has no bind parameters.
    #[error("this engine does not support bind parameters, which editing needs")]
    NoParameters,
    /// The result does not come from one table (a join, an expression, a statement the grid
    /// does not know the source of).
    #[error("the result does not come from a single table")]
    NotSingleTable,
    /// The table's metadata could not be read completely (the column list was cut).
    #[error("the table's columns could not all be read")]
    IncompleteMetadata,
    /// No primary key or usable unique key (P5-B review M1 rules).
    #[error(
        "the table has no primary key or unique key that identifies rows: rows cannot be edited"
    )]
    NoKey,
    /// The table's storage engine has no transactions ([`TableInfo::transactional`]
    /// `Some(false)`, MySQL MyISAM / MEMORY / ARCHIVE): a failed save could not be rolled back,
    /// so editing is refused.
    #[error(
        "the table's storage engine has no transactions, so a failed save could not be rolled back: rows cannot be edited"
    )]
    NotTransactional,
    /// A key column is not in the result (or appears twice): rows cannot be identified.
    #[error("the result does not include every key column ({}) exactly once", .0.join(", "))]
    KeyNotInResult(Vec<String>),
}

/// The DML name parts of a table path: its nearest schema (else its catalog) and its name.
#[must_use]
pub fn table_parts(path: &ObjectPath) -> Vec<String> {
    let Some((leaf, parents)) = path.0.split_last() else {
        return Vec::new();
    };
    let container = parents
        .iter()
        .rev()
        .find(|s| s.kind == ObjectKind::Schema)
        .or_else(|| parents.iter().rev().find(|s| s.kind == ObjectKind::Catalog));
    match container {
        Some(c) => vec![c.name.clone(), leaf.name.clone()],
        None => vec![leaf.name.clone()],
    }
}

impl EditableTable {
    /// The editable view of a table from its metadata: the table's own listing entry (for
    /// [`TableInfo::transactional`]; `None` when unknown), its columns (every one: pass
    /// `columns_complete = false` when the listing was cut) and its indexes.
    ///
    /// The key is chosen with [`choose_row_key`] among the unique indexes
    /// ([`KeyCandidate::from_index`], from the driver's flags only: invalid, deferrable, partial
    /// and expression indexes never count) whose columns all exist in `columns`, plus, on
    /// SQLite, the `INTEGER PRIMARY KEY` column (an alias of the rowid, which has no index entry)
    /// taken from [`ColumnInfo::primary_key`](ninesql_driver_api::ColumnInfo::primary_key).
    ///
    /// # Errors
    /// [`NotEditable::IncompleteMetadata`], [`NotEditable::NotTransactional`],
    /// [`NotEditable::NoKey`].
    pub fn from_metadata(
        engine: &EngineId,
        path: ObjectPath,
        table: Option<&TableInfo>,
        columns: &[ObjectInfo],
        columns_complete: bool,
        indexes: &[ObjectInfo],
    ) -> Result<Self, NotEditable> {
        if !columns_complete {
            return Err(NotEditable::IncompleteMetadata);
        }
        let transactional = table.and_then(|t| t.transactional);
        if transactional == Some(false) {
            return Err(NotEditable::NotTransactional);
        }
        let mut cols: Vec<(u32, TableColumn)> = columns
            .iter()
            .filter_map(|o| match &o.details {
                ObjectDetails::Column(c) => Some((
                    c.ordinal,
                    TableColumn {
                        name: o.name().to_owned(),
                        data_type: c.data_type.clone(),
                        nullable: c.nullable,
                        primary_key: c.primary_key,
                        auto_generated: c.auto_generated,
                        has_default: c.default.is_some(),
                    },
                )),
                _ => None,
            })
            .collect();
        cols.sort_by_key(|(ordinal, _)| *ordinal);
        let columns: Vec<TableColumn> = cols.into_iter().map(|(_, c)| c).collect();
        let column = |name: &str| columns.iter().find(|c| c.name == name);

        let mut candidates: Vec<KeyCandidate> = indexes
            .iter()
            .filter_map(|o| match &o.details {
                ObjectDetails::Index(info) => {
                    let known: Option<Vec<&TableColumn>> =
                        info.columns.iter().map(|n| column(n)).collect();
                    let known = known?;
                    let not_null = !known.is_empty() && known.iter().all(|c| !c.nullable);
                    KeyCandidate::from_index(info, not_null)
                }
                _ => None,
            })
            .collect();
        if *engine == EngineId::SQLITE {
            let pk: Vec<&TableColumn> = columns.iter().filter(|c| c.primary_key).collect();
            if let [only] = pk[..]
                && only.data_type.trim().eq_ignore_ascii_case("integer")
            {
                let mut c = KeyCandidate::new(vec![only.name.clone()]);
                c.primary = true;
                c.not_null = true;
                c.expression = false;
                c.valid = true;
                candidates.push(c);
            }
        }
        let (key_columns, kind) = choose_row_key(&candidates).ok_or(NotEditable::NoKey)?;
        Ok(Self {
            table: table_parts(&path),
            path,
            columns,
            key: RowKey {
                columns: key_columns,
                kind,
            },
            transactional,
        })
    }

    /// The column named `name`.
    #[must_use]
    pub fn column(&self, name: &str) -> Option<&TableColumn> {
        self.columns.iter().find(|c| c.name == name)
    }
}

impl fmt::Display for RowKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.columns.join(", "))
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used, clippy::expect_used)] // Tests may panic (AGENTS.md).
mod tests {
    use ninesql_driver_api::{ColumnInfo, IndexInfo};

    use super::*;

    fn table() -> ObjectPath {
        ObjectPath::root()
            .child(ObjectKind::Schema, "public")
            .child(ObjectKind::Table, "t")
    }

    fn col(name: &str, ordinal: u32, ty: &str, nullable: bool, pk: bool) -> ObjectInfo {
        let mut c = ColumnInfo::new(ordinal, ty);
        c.nullable = nullable;
        c.primary_key = pk;
        ObjectInfo {
            path: table().child(ObjectKind::Column, name),
            comment: None,
            details: ObjectDetails::Column(c),
        }
    }

    fn index(name: &str, cols: &[&str], f: impl FnOnce(&mut IndexInfo)) -> ObjectInfo {
        let mut i = IndexInfo::default();
        i.columns = cols.iter().map(|c| (*c).to_owned()).collect();
        i.expressions = vec![false; cols.len()];
        i.valid = true;
        i.unique = true;
        f(&mut i);
        ObjectInfo {
            path: table().child(ObjectKind::Index, name),
            comment: None,
            details: ObjectDetails::Index(i),
        }
    }

    #[test]
    fn primary_key_wins_and_parts_are_schema_and_name() {
        let cols = [
            col("id", 1, "bigint", false, true),
            col("email", 2, "text", false, false),
        ];
        let idx = [
            index("u_email", &["email"], |_| {}),
            index("pk", &["id"], |i| i.primary = true),
        ];
        let t =
            EditableTable::from_metadata(&EngineId::POSTGRESQL, table(), None, &cols, true, &idx)
                .unwrap();
        assert_eq!(t.key.columns, vec!["id"]);
        assert_eq!(t.key.kind, KeyKind::PrimaryKey);
        assert_eq!(t.table, vec!["public", "t"]);
    }

    #[test]
    fn unusable_indexes_never_count() {
        let cols = [col("a", 1, "int", false, false)];
        for f in [
            (|i: &mut IndexInfo| i.valid = false) as fn(&mut IndexInfo),
            |i| i.partial = true,
            |i| i.deferrable = true,
            |i| i.expressions = vec![true],
            |i| i.unique = false,
        ] {
            let idx = [index("x", &["a"], f)];
            assert_eq!(
                EditableTable::from_metadata(
                    &EngineId::POSTGRESQL,
                    table(),
                    None,
                    &cols,
                    true,
                    &idx
                ),
                Err(NotEditable::NoKey)
            );
        }
        // An index on a column that is not listed (an expression reported by name) is ignored.
        let idx = [index("x", &["lower(a)"], |_| {})];
        assert_eq!(
            EditableTable::from_metadata(&EngineId::POSTGRESQL, table(), None, &cols, true, &idx),
            Err(NotEditable::NoKey)
        );
    }

    #[test]
    fn sqlite_integer_primary_key_and_refusals() {
        let cols = [
            col("id", 1, "INTEGER", true, true),
            col("v", 2, "TEXT", true, false),
        ];
        let t = EditableTable::from_metadata(&EngineId::SQLITE, table(), None, &cols, true, &[])
            .unwrap();
        assert_eq!(t.key.columns, vec!["id"]);
        // Not on another engine, and not for another type.
        assert_eq!(
            EditableTable::from_metadata(&EngineId::POSTGRESQL, table(), None, &cols, true, &[]),
            Err(NotEditable::NoKey)
        );
        let cols2 = [col("id", 1, "INT", true, true)];
        assert_eq!(
            EditableTable::from_metadata(&EngineId::SQLITE, table(), None, &cols2, true, &[]),
            Err(NotEditable::NoKey)
        );
        let mut info = TableInfo::default();
        info.transactional = Some(false);
        assert_eq!(
            EditableTable::from_metadata(&EngineId::SQLITE, table(), Some(&info), &cols, true, &[]),
            Err(NotEditable::NotTransactional)
        );
        assert_eq!(
            EditableTable::from_metadata(&EngineId::SQLITE, table(), None, &cols, false, &[]),
            Err(NotEditable::IncompleteMetadata)
        );
    }

    #[test]
    fn nullable_unique_key_is_a_last_resort() {
        let cols = [
            col("a", 1, "int", true, false),
            col("b", 2, "int", false, false),
            col("c", 3, "int", false, false),
        ];
        let idx = [
            index("ua", &["a"], |_| {}),
            index("ubc", &["b", "c"], |_| {}),
        ];
        let t = EditableTable::from_metadata(&EngineId::MYSQL, table(), None, &cols, true, &idx)
            .unwrap();
        assert_eq!(t.key.columns, vec!["b", "c"]);
        assert_eq!(
            t.key.kind,
            KeyKind::Unique {
                nulls_distinct: true
            }
        );
    }
}
