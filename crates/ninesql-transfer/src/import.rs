//! The engine-independent part of the CSV import (F-XFER-03): target column types, the column
//! mapping, value conversion into typed bind parameters, the preview, and a row source that turns
//! the file into batches of parameter rows with bounded memory.
//!
//! Sending the rows (transactions, confirmation, cancel) is `ninesql-core`'s job
//! (`TransferService::import_csv`). Nothing here logs or reports a value: issues carry a line, a
//! column name and a reason (I1).

use std::io::BufRead;

use ninesql_driver_api::Param;

use crate::csv::{CsvFormat, CsvLimits, CsvReader, RecordErrorKind};
use crate::error::TransferError;
use crate::value::days_from_civil;

/// What a target column accepts, from its engine type name.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum TargetType {
    /// Integers (`int`, `bigint`, `serial`…). Digits beyond `i64` are sent as a decimal.
    Integer,
    /// Floating point (`real`, `double precision`, `float`…).
    Float,
    /// Exact decimals (`numeric`, `decimal`).
    Decimal,
    /// Booleans: `true` / `false`, `t` / `f`, `yes` / `no`, `y` / `n`, `1` / `0`.
    Boolean,
    /// Dates: `YYYY-MM-DD`.
    Date,
    /// Timestamps: `YYYY-MM-DD[ T]HH:MM[:SS[.fraction]]`, with an offset (`Z`, `+02`, `-05:30`)
    /// only when `zoned`.
    Timestamp {
        /// The column holds instants (`timestamptz`): an offset is applied and the value sent
        /// in UTC.
        zoned: bool,
    },
    /// Binary: `\x…` or `0x…` hex.
    Binary,
    /// JSON text (sent as JSON; the engine validates it).
    Json,
    /// Anything else, sent as text for the engine to convert.
    Text,
}

impl TargetType {
    /// Classifies an engine type name (`character varying(20)`, `bigint unsigned`,
    /// `timestamp with time zone`…). Unknown names are [`TargetType::Text`].
    #[must_use]
    pub fn from_engine_type(name: &str) -> Self {
        let lower = name.trim().to_ascii_lowercase();
        let base = lower.split('(').next().unwrap_or("").trim();
        let first = base.split_whitespace().next().unwrap_or("");
        if lower.contains("with time zone") || base == "timestamptz" {
            return Self::Timestamp { zoned: true };
        }
        match first {
            "int" | "integer" | "smallint" | "bigint" | "tinyint" | "mediumint" | "int2"
            | "int4" | "int8" | "serial" | "bigserial" | "smallserial" | "serial4" | "serial8"
            | "serial2" => Self::Integer,
            "real" | "float" | "double" | "float4" | "float8" => Self::Float,
            "numeric" | "decimal" | "dec" | "number" => Self::Decimal,
            "bool" | "boolean" => Self::Boolean,
            "date" => Self::Date,
            "timestamp" | "datetime" => Self::Timestamp { zoned: false },
            "bytea" | "blob" | "binary" | "varbinary" | "tinyblob" | "mediumblob" | "longblob" => {
                Self::Binary
            }
            "json" | "jsonb" => Self::Json,
            _ => Self::Text,
        }
    }

    /// Short name for issues and the preview.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Integer => "integer",
            Self::Float => "float",
            Self::Decimal => "decimal",
            Self::Boolean => "boolean",
            Self::Date => "date",
            Self::Timestamp { zoned: false } => "timestamp",
            Self::Timestamp { zoned: true } => "timestamp with time zone",
            Self::Binary => "binary",
            Self::Json => "json",
            Self::Text => "text",
        }
    }
}

/// A column of the target table, from the metadata service (`ColumnInfo`).
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct TargetColumn {
    /// Column name.
    pub name: String,
    /// Engine type name.
    pub data_type: String,
    /// Accepts NULL.
    pub nullable: bool,
    /// Has a default or is generated by the engine (a NULL may still be refused by it).
    pub has_default: bool,
}

impl TargetColumn {
    /// A nullable column without default.
    #[must_use]
    pub fn new(name: impl Into<String>, data_type: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            data_type: data_type.into(),
            nullable: true,
            has_default: false,
        }
    }

    /// From the driver API's `ColumnInfo` and the column's name.
    #[must_use]
    pub fn from_info(name: impl Into<String>, info: &ninesql_driver_api::ColumnInfo) -> Self {
        Self {
            name: name.into(),
            data_type: info.data_type.clone(),
            nullable: info.nullable,
            has_default: info.default.is_some() || info.auto_generated,
        }
    }

    /// Sets `nullable`.
    #[must_use]
    pub fn with_nullable(mut self, nullable: bool) -> Self {
        self.nullable = nullable;
        self
    }

    /// The type class.
    #[must_use]
    pub fn target_type(&self) -> TargetType {
        TargetType::from_engine_type(&self.data_type)
    }
}

/// One mapped column: source field `source` goes to target column `target` (0-based).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct MappedColumn {
    /// Index of the field in the file.
    pub source: usize,
    /// Index of the target column.
    pub target: usize,
}

/// Which file fields go to which target columns. Unmapped fields are skipped; unmapped target
/// columns get their default.
#[derive(Clone, Debug, PartialEq, Eq, Default)]
pub struct ColumnMapping {
    /// The mapped columns, in insert order.
    pub columns: Vec<MappedColumn>,
}

/// How a mapping is suggested.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
#[non_exhaustive]
pub enum MappingMode {
    /// Header name to column name, ignoring ASCII case and surrounding blanks (needs a header).
    #[default]
    ByName,
    /// Field `i` to column `i`.
    ByPosition,
}

impl ColumnMapping {
    /// Maps header names to target names (ASCII case-insensitive, trimmed). Unmatched header
    /// fields are skipped.
    #[must_use]
    pub fn by_name(header: &[String], targets: &[TargetColumn]) -> Self {
        let mut columns = Vec::new();
        for (source, name) in header.iter().enumerate() {
            let name = name.trim();
            if let Some(target) = targets
                .iter()
                .position(|t| t.name.eq_ignore_ascii_case(name))
                && !columns.iter().any(|c: &MappedColumn| c.target == target)
            {
                columns.push(MappedColumn { source, target });
            }
        }
        Self { columns }
    }

    /// Maps field `i` to column `i` for the first `min(fields, targets)` columns.
    #[must_use]
    pub fn by_position(fields: usize, targets: &[TargetColumn]) -> Self {
        Self {
            columns: (0..fields.min(targets.len()))
                .map(|i| MappedColumn {
                    source: i,
                    target: i,
                })
                .collect(),
        }
    }

    /// Stops importing source field `source`.
    pub fn skip_source(&mut self, source: usize) {
        self.columns.retain(|c| c.source != source);
    }

    /// Checks the mapping against `targets`.
    ///
    /// # Errors
    /// [`TransferError::InvalidOption`]: empty, a target out of range or mapped twice.
    pub fn validate(&self, targets: &[TargetColumn]) -> Result<(), TransferError> {
        if self.columns.is_empty() {
            return Err(TransferError::InvalidOption("no column is mapped".into()));
        }
        for (i, c) in self.columns.iter().enumerate() {
            if c.target >= targets.len() {
                return Err(TransferError::InvalidOption(
                    "a mapping points past the target columns".into(),
                ));
            }
            if self.columns[..i].iter().any(|o| o.target == c.target) {
                return Err(TransferError::InvalidOption(format!(
                    "column {} is mapped twice",
                    targets[c.target].name
                )));
            }
        }
        Ok(())
    }
}

/// Blank trimming of field values.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
#[non_exhaustive]
pub enum Trim {
    /// Values are taken as they are (default).
    #[default]
    None,
    /// Leading and trailing blanks are removed before the NULL check and the conversion.
    Both,
}

/// How field text becomes a value.
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct ValueOptions {
    /// A field equal to this text is NULL (for example `NULL` or `\N`).
    pub null_text: Option<String>,
    /// An empty field is NULL (default `true`); otherwise it is an empty text (and an error for
    /// non-text columns).
    pub empty_is_null: bool,
    /// Trimming.
    pub trim: Trim,
}

impl Default for ValueOptions {
    fn default() -> Self {
        Self {
            null_text: None,
            empty_is_null: true,
            trim: Trim::None,
        }
    }
}

/// Why a field could not be converted.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum ConvertError {
    /// The text is not a value of the column's type.
    Invalid(TargetType),
    /// A time-zone offset for a column without time zone.
    UnexpectedOffset,
}

fn is_strict_decimal(s: &str) -> bool {
    let s = s.strip_prefix(['-', '+']).unwrap_or(s);
    let (int, frac) = s.split_once('.').unwrap_or((s, ""));
    (!int.is_empty() || !frac.is_empty())
        && int.bytes().all(|b| b.is_ascii_digit())
        && frac.bytes().all(|b| b.is_ascii_digit())
}

fn parse_hex(s: &str) -> Option<Vec<u8>> {
    let digits = s
        .strip_prefix("\\x")
        .or_else(|| s.strip_prefix("0x"))
        .or_else(|| s.strip_prefix("0X"))?;
    if digits.len() % 2 != 0 {
        return None;
    }
    let val = |b: u8| match b {
        b'0'..=b'9' => Some(b - b'0'),
        b'a'..=b'f' => Some(b - b'a' + 10),
        b'A'..=b'F' => Some(b - b'A' + 10),
        _ => None,
    };
    digits
        .as_bytes()
        .chunks(2)
        .map(|p| Some(val(p[0])? << 4 | val(p[1])?))
        .collect()
}

fn digits(s: &str, n: usize) -> Option<u32> {
    if s.len() == n && s.bytes().all(|b| b.is_ascii_digit()) {
        s.parse().ok()
    } else {
        None
    }
}

/// `YYYY-MM-DD` → days since 1970-01-01, checking the day exists.
#[must_use]
pub fn parse_date(s: &str) -> Option<i64> {
    let mut parts = s.splitn(3, '-');
    let y = digits(parts.next()?, 4)?;
    let m = digits(parts.next()?, 2)?;
    let d = digits(parts.next()?, 2)?;
    if !(1..=12).contains(&m) || d == 0 {
        return None;
    }
    let leap = (y % 4 == 0 && y % 100 != 0) || y % 400 == 0;
    let max = match m {
        2 if leap => 29,
        2 => 28,
        4 | 6 | 9 | 11 => 30,
        _ => 31,
    };
    (d <= max).then(|| days_from_civil(i64::from(y), m, d))
}

/// A parsed timestamp: microseconds since the epoch (UTC when an offset was given) and whether
/// an offset was given.
fn parse_timestamp(s: &str) -> Option<(i64, bool)> {
    if s.len() < 16 {
        return None;
    }
    let (date, rest) = s.split_at(10);
    let days = parse_date(date)?;
    let rest = rest.strip_prefix([' ', 'T'])?;
    // Offset: `Z`, or the last `+` / `-` after the clock.
    let (clock, offset_secs, has_offset) = if let Some(c) = rest.strip_suffix(['Z', 'z']) {
        (c, 0i64, true)
    } else if let Some(pos) = rest.rfind(['+', '-']) {
        let (c, off) = rest.split_at(pos);
        let sign = if off.starts_with('-') { -1 } else { 1 };
        let off = &off[1..];
        let (h, m) = match off.split_once(':') {
            Some((h, m)) => (digits(h, 2)?, digits(m, 2)?),
            None if off.len() == 4 => (digits(&off[..2], 2)?, digits(&off[2..], 2)?),
            None => (digits(off, 2)?, 0),
        };
        if h > 23 || m > 59 {
            return None;
        }
        (c, sign * i64::from(h * 3600 + m * 60), true)
    } else {
        (rest, 0, false)
    };
    let mut parts = clock.splitn(3, ':');
    let h = digits(parts.next()?, 2)?;
    let mi = digits(parts.next()?, 2)?;
    let (sec, micros) = match parts.next() {
        None => (0, 0),
        Some(sec) => {
            let (whole, frac) = sec.split_once('.').unwrap_or((sec, ""));
            let whole = digits(whole, 2)?;
            if frac.len() > 9 || !frac.bytes().all(|b| b.is_ascii_digit()) {
                return None;
            }
            let mut f = frac.to_owned();
            f.truncate(6);
            while f.len() < 6 {
                f.push('0');
            }
            (whole, f.parse::<i64>().ok()?)
        }
    };
    if h > 23 || mi > 59 || sec > 60 {
        return None;
    }
    let secs = days * 86_400 + i64::from(h * 3600 + mi * 60 + sec) - offset_secs;
    Some((
        secs.checked_mul(1_000_000)?.checked_add(micros)?,
        has_offset,
    ))
}

/// Converts one field into the bind parameter for a column of type `ty` (NULL handling and
/// trimming included).
///
/// # Errors
/// [`ConvertError`]: the text is not a value of the type.
pub fn convert(text: &str, ty: TargetType, options: &ValueOptions) -> Result<Param, ConvertError> {
    let text = match options.trim {
        Trim::None => text,
        Trim::Both => text.trim(),
    };
    if options.null_text.as_deref() == Some(text) || (text.is_empty() && options.empty_is_null) {
        return Ok(Param::Null);
    }
    let invalid = || ConvertError::Invalid(ty);
    Ok(match ty {
        TargetType::Integer => match text.parse::<i64>() {
            Ok(i) => Param::Int(i),
            Err(_) if is_strict_decimal(text) && !text.contains('.') => {
                Param::Decimal(text.trim_start_matches('+').to_owned())
            }
            Err(_) => return Err(invalid()),
        },
        TargetType::Float => {
            let f: f64 = text.parse().map_err(|_| invalid())?;
            Param::Float(f)
        }
        TargetType::Decimal => {
            if !is_strict_decimal(text) {
                return Err(invalid());
            }
            let t = text.trim_start_matches('+');
            let t = if t.starts_with('.') {
                format!("0{t}")
            } else if let Some(r) = t.strip_prefix("-.") {
                format!("-0.{r}")
            } else {
                t.to_owned()
            };
            Param::Decimal(t.trim_end_matches('.').to_owned())
        }
        TargetType::Boolean => match text.to_ascii_lowercase().as_str() {
            "true" | "t" | "yes" | "y" | "1" => Param::Bool(true),
            "false" | "f" | "no" | "n" | "0" => Param::Bool(false),
            _ => return Err(invalid()),
        },
        TargetType::Date => Param::Date(
            i32::try_from(parse_date(text).ok_or_else(invalid)?).map_err(|_| invalid())?,
        ),
        TargetType::Timestamp { zoned } => {
            let (micros, has_offset) = parse_timestamp(text).ok_or_else(invalid)?;
            if has_offset && !zoned {
                return Err(ConvertError::UnexpectedOffset);
            }
            Param::Timestamp {
                micros,
                utc: has_offset,
            }
        }
        TargetType::Binary => Param::Bytes(parse_hex(text).ok_or_else(invalid)?),
        TargetType::Json => Param::Json(text.to_owned()),
        TargetType::Text => Param::Text(text.to_owned()),
    })
}

/// What is wrong with one row.
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum IssueKind {
    /// The record could not be read.
    Record(RecordErrorKind),
    /// The record has fewer fields than a mapped column needs.
    MissingField {
        /// Fields found.
        found: usize,
    },
    /// A field could not be converted for its column.
    Conversion {
        /// Target column.
        column: String,
        /// Expected type.
        expected: TargetType,
    },
    /// A time-zone offset for a column without time zone.
    UnexpectedOffset {
        /// Target column.
        column: String,
    },
    /// NULL for a column that refuses NULL and has no default.
    NullNotAllowed {
        /// Target column.
        column: String,
    },
    /// The engine refused the batch holding this line (bulk statements fail as a whole).
    Rejected,
}

/// An issue on one line. Never holds a value.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct RowIssue {
    /// 1-based line where the record starts.
    pub line: u64,
    /// What is wrong.
    pub kind: IssueKind,
}

impl RowIssue {
    /// A user-presentable description (no value).
    #[must_use]
    pub fn describe(&self) -> String {
        match &self.kind {
            IssueKind::Record(k) => format!("line {}: {}", self.line, k.as_str()),
            IssueKind::MissingField { found } => {
                format!("line {}: only {found} field(s)", self.line)
            }
            IssueKind::Conversion { column, expected } => format!(
                "line {}: column {column}: not a valid {}",
                self.line,
                expected.as_str()
            ),
            IssueKind::UnexpectedOffset { column } => format!(
                "line {}: column {column}: a time-zone offset for a column without time zone",
                self.line
            ),
            IssueKind::NullNotAllowed { column } => {
                format!("line {}: column {column}: NULL is not allowed", self.line)
            }
            IssueKind::Rejected => format!("line {}: rejected by the database", self.line),
        }
    }
}

/// The type a column of the file seems to hold, from the preview rows.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum GuessedType {
    /// Every value was empty or NULL.
    Empty,
    /// Integers.
    Integer,
    /// Numbers with a fraction or an exponent.
    Float,
    /// Booleans (`true` / `false`).
    Boolean,
    /// `YYYY-MM-DD` dates.
    Date,
    /// Timestamps.
    Timestamp,
    /// Anything else.
    Text,
}

fn guess_one(text: &str) -> GuessedType {
    if text.parse::<i64>().is_ok() {
        GuessedType::Integer
    } else if text.parse::<f64>().is_ok() && text.bytes().any(|b| b.is_ascii_digit()) {
        GuessedType::Float
    } else if text.eq_ignore_ascii_case("true") || text.eq_ignore_ascii_case("false") {
        GuessedType::Boolean
    } else if parse_date(text).is_some() {
        GuessedType::Date
    } else if parse_timestamp(text).is_some() {
        GuessedType::Timestamp
    } else {
        GuessedType::Text
    }
}

fn merge_guess(a: GuessedType, b: GuessedType) -> GuessedType {
    use GuessedType::{Empty, Float, Integer, Text};
    match (a, b) {
        (Empty, x) | (x, Empty) => x,
        (x, y) if x == y => x,
        (Integer, Float) | (Float, Integer) => Float,
        _ => Text,
    }
}

/// One row of the preview. `Debug` shows the line and the field count only: the fields are
/// shown to the user, never logged.
#[derive(Clone, PartialEq, Eq)]
pub struct PreviewRow {
    /// 1-based line.
    pub line: u64,
    /// The fields as read (before trimming and conversion).
    pub fields: Vec<String>,
}

impl std::fmt::Debug for PreviewRow {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("PreviewRow")
            .field("line", &self.line)
            .field("fields", &self.fields.len())
            .finish()
    }
}

/// The preview of a CSV file against a target table.
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct CsvPreview {
    /// Header names, when the format has a header.
    pub header: Option<Vec<String>>,
    /// The first rows.
    pub rows: Vec<PreviewRow>,
    /// Fields per record (from the header, else the first record).
    pub field_count: usize,
    /// The guessed type of each file column.
    pub guessed: Vec<GuessedType>,
    /// The suggested mapping ([`MappingMode`]).
    pub mapping: ColumnMapping,
    /// The type each target column expects.
    pub target_types: Vec<TargetType>,
    /// Issues found in the previewed rows, with the suggested mapping (at most one per row
    /// per column).
    pub issues: Vec<RowIssue>,
    /// The file is shorter than the preview: every row was read.
    pub complete: bool,
}

/// Largest preview, in rows.
pub const MAX_PREVIEW_ROWS: usize = 1000;

/// Reads the first `rows` rows (at most [`MAX_PREVIEW_ROWS`]) of `input` and checks them against
/// `targets` with a mapping suggested by `mode`.
///
/// # Errors
/// Fatal CSV errors ([`CsvReader::next_record`]), invalid options.
pub fn preview<R: BufRead>(
    input: R,
    format: CsvFormat,
    limits: CsvLimits,
    values: &ValueOptions,
    targets: &[TargetColumn],
    mode: MappingMode,
    rows: usize,
) -> Result<CsvPreview, TransferError> {
    let mut reader = CsvReader::new(input, format, limits)?;
    let header = if format.header {
        match reader.next_non_blank()? {
            Some(Ok(r)) => Some(r.fields),
            Some(Err(e)) => {
                return Err(TransferError::Csv {
                    line: e.line,
                    reason: format!("the header cannot be read: {}", e.kind.as_str()),
                });
            }
            None => Some(Vec::new()),
        }
    } else {
        None
    };
    let mut out_rows = Vec::new();
    let mut issues = Vec::new();
    let limit = rows.min(MAX_PREVIEW_ROWS);
    let mut complete = true;
    while out_rows.len() < limit {
        match reader.next_non_blank()? {
            None => break,
            Some(Ok(r)) => out_rows.push(PreviewRow {
                line: r.line,
                fields: r.fields,
            }),
            Some(Err(e)) => issues.push(RowIssue {
                line: e.line,
                kind: IssueKind::Record(e.kind),
            }),
        }
    }
    if out_rows.len() == limit && reader.next_non_blank()?.is_some() {
        complete = false;
    }
    let field_count = header
        .as_ref()
        .map(Vec::len)
        .or_else(|| out_rows.first().map(|r| r.fields.len()))
        .unwrap_or(0);
    let mapping = match (mode, &header) {
        (MappingMode::ByName, Some(h)) => ColumnMapping::by_name(h, targets),
        _ => ColumnMapping::by_position(field_count, targets),
    };
    let mut guessed = vec![GuessedType::Empty; field_count];
    for row in &out_rows {
        for (i, g) in guessed.iter_mut().enumerate() {
            if let Some(f) = row.fields.get(i) {
                let f = match values.trim {
                    Trim::None => f.as_str(),
                    Trim::Both => f.trim(),
                };
                if f.is_empty() || values.null_text.as_deref() == Some(f) {
                    continue;
                }
                *g = merge_guess(*g, guess_one(f));
            }
        }
        let mut sink = Vec::new();
        convert_row(row.line, &row.fields, &mapping, targets, values, &mut sink);
        if let Err(issue) = check_row(&sink, row.line, &mapping, targets) {
            issues.push(issue);
        }
        if let Some(issue) = take_issue(&mut sink) {
            issues.push(issue);
        }
    }
    issues.sort_by_key(|i| i.line);
    Ok(CsvPreview {
        header,
        rows: out_rows,
        field_count,
        guessed,
        mapping,
        target_types: targets.iter().map(TargetColumn::target_type).collect(),
        issues,
        complete,
    })
}

/// Result of converting one row: the parameters, or the first issue.
enum Converted {
    Row(Vec<Param>),
    Issue(RowIssue),
}

fn take_issue(sink: &mut Vec<Converted>) -> Option<RowIssue> {
    match sink.pop() {
        Some(Converted::Issue(i)) => Some(i),
        _ => None,
    }
}

fn check_row(
    sink: &[Converted],
    line: u64,
    mapping: &ColumnMapping,
    targets: &[TargetColumn],
) -> Result<(), RowIssue> {
    if let Some(Converted::Row(params)) = sink.last() {
        for (p, c) in params.iter().zip(&mapping.columns) {
            let t = &targets[c.target];
            if matches!(p, Param::Null) && !t.nullable && !t.has_default {
                return Err(RowIssue {
                    line,
                    kind: IssueKind::NullNotAllowed {
                        column: t.name.clone(),
                    },
                });
            }
        }
    }
    Ok(())
}

fn convert_row(
    line: u64,
    fields: &[String],
    mapping: &ColumnMapping,
    targets: &[TargetColumn],
    values: &ValueOptions,
    sink: &mut Vec<Converted>,
) {
    let mut params = Vec::with_capacity(mapping.columns.len());
    for c in &mapping.columns {
        let Some(text) = fields.get(c.source) else {
            sink.push(Converted::Issue(RowIssue {
                line,
                kind: IssueKind::MissingField {
                    found: fields.len(),
                },
            }));
            return;
        };
        let target = &targets[c.target];
        match convert(text, target.target_type(), values) {
            Ok(p) => params.push(p),
            Err(ConvertError::Invalid(expected)) => {
                sink.push(Converted::Issue(RowIssue {
                    line,
                    kind: IssueKind::Conversion {
                        column: target.name.clone(),
                        expected,
                    },
                }));
                return;
            }
            Err(ConvertError::UnexpectedOffset) => {
                sink.push(Converted::Issue(RowIssue {
                    line,
                    kind: IssueKind::UnexpectedOffset {
                        column: target.name.clone(),
                    },
                }));
                return;
            }
        }
    }
    sink.push(Converted::Row(params));
}

/// A batch of rows ready to insert.
#[derive(Clone, PartialEq)]
pub struct RowBatch {
    /// One parameter vector per row, in the mapping's column order.
    pub rows: Vec<Vec<Param>>,
    /// Line of each row, for error reports.
    pub lines: Vec<u64>,
    /// Rows of this stretch of the file that were skipped, with why.
    pub issues: Vec<RowIssue>,
    /// Estimated bytes of the parameters.
    pub bytes: usize,
}

impl std::fmt::Debug for RowBatch {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("RowBatch")
            .field("rows", &self.rows.len())
            .field("issues", &self.issues.len())
            .field("bytes", &self.bytes)
            .finish()
    }
}

fn param_bytes(p: &Param) -> usize {
    16 + match p {
        Param::Decimal(s) | Param::Text(s) | Param::Json(s) => s.len(),
        Param::Bytes(b) => b.len(),
        _ => 0,
    }
}

/// Reads a CSV file as batches of parameter rows for the mapped columns.
pub struct RowSource<R> {
    reader: CsvReader<R>,
    mapping: ColumnMapping,
    targets: Vec<TargetColumn>,
    values: ValueOptions,
    header: Option<Vec<String>>,
    done: bool,
}

impl<R> std::fmt::Debug for RowSource<R> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("RowSource")
            .field("columns", &self.mapping.columns.len())
            .field("done", &self.done)
            .finish_non_exhaustive()
    }
}

impl<R: BufRead> RowSource<R> {
    /// Opens the source, reading the header when the format has one.
    ///
    /// # Errors
    /// Invalid options or mapping; fatal CSV errors; an unreadable header.
    pub fn open(
        input: R,
        format: CsvFormat,
        limits: CsvLimits,
        values: ValueOptions,
        targets: Vec<TargetColumn>,
        mapping: ColumnMapping,
    ) -> Result<Self, TransferError> {
        mapping.validate(&targets)?;
        let mut reader = CsvReader::new(input, format, limits)?;
        let header = if format.header {
            match reader.next_non_blank()? {
                Some(Ok(r)) => Some(r.fields),
                Some(Err(e)) => {
                    return Err(TransferError::Csv {
                        line: e.line,
                        reason: format!("the header cannot be read: {}", e.kind.as_str()),
                    });
                }
                None => None,
            }
        } else {
            None
        };
        Ok(Self {
            reader,
            mapping,
            targets,
            values,
            header,
            done: false,
        })
    }

    /// The header, when the file has one.
    #[must_use]
    pub fn header(&self) -> Option<&[String]> {
        self.header.as_deref()
    }

    /// The mapping.
    #[must_use]
    pub fn mapping(&self) -> &ColumnMapping {
        &self.mapping
    }

    /// The target column names, in insert order.
    #[must_use]
    pub fn column_names(&self) -> Vec<String> {
        self.mapping
            .columns
            .iter()
            .map(|c| self.targets[c.target].name.clone())
            .collect()
    }

    /// Bytes of the file read so far.
    #[must_use]
    pub fn bytes_read(&self) -> u64 {
        self.reader.bytes_read()
    }

    /// The next batch of at most `max_rows` valid rows (and at most about `max_bytes` of
    /// parameters), or `None` at the end. Invalid rows are not in `rows`: they are reported in
    /// `issues`.
    ///
    /// # Errors
    /// Fatal CSV errors.
    pub fn next_batch(
        &mut self,
        max_rows: usize,
        max_bytes: usize,
    ) -> Result<Option<RowBatch>, TransferError> {
        if self.done {
            return Ok(None);
        }
        let mut batch = RowBatch {
            rows: Vec::with_capacity(max_rows.min(1024)),
            lines: Vec::new(),
            issues: Vec::new(),
            bytes: 0,
        };
        let mut sink = Vec::with_capacity(1);
        while batch.rows.len() < max_rows.max(1) && batch.bytes < max_bytes {
            match self.reader.next_non_blank()? {
                None => {
                    self.done = true;
                    break;
                }
                Some(Err(e)) => batch.issues.push(RowIssue {
                    line: e.line,
                    kind: IssueKind::Record(e.kind),
                }),
                Some(Ok(record)) => {
                    convert_row(
                        record.line,
                        &record.fields,
                        &self.mapping,
                        &self.targets,
                        &self.values,
                        &mut sink,
                    );
                    if let Err(issue) = check_row(&sink, record.line, &self.mapping, &self.targets)
                    {
                        sink.clear();
                        batch.issues.push(issue);
                        continue;
                    }
                    match sink.pop() {
                        Some(Converted::Row(params)) => {
                            batch.bytes += params.iter().map(param_bytes).sum::<usize>();
                            batch.rows.push(params);
                            batch.lines.push(record.line);
                        }
                        Some(Converted::Issue(issue)) => batch.issues.push(issue),
                        None => {}
                    }
                }
            }
        }
        if batch.rows.is_empty() && batch.issues.is_empty() && self.done {
            return Ok(None);
        }
        Ok(Some(batch))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn engine_types() {
        assert_eq!(
            TargetType::from_engine_type("bigint unsigned"),
            TargetType::Integer
        );
        assert_eq!(
            TargetType::from_engine_type("character varying(20)"),
            TargetType::Text
        );
        assert_eq!(
            TargetType::from_engine_type("timestamp with time zone"),
            TargetType::Timestamp { zoned: true }
        );
        assert_eq!(
            TargetType::from_engine_type("TIMESTAMP(6) WITHOUT TIME ZONE"),
            TargetType::Timestamp { zoned: false }
        );
        assert_eq!(
            TargetType::from_engine_type("numeric(10,2)"),
            TargetType::Decimal
        );
        assert_eq!(
            TargetType::from_engine_type("double precision"),
            TargetType::Float
        );
        assert_eq!(TargetType::from_engine_type("uuid"), TargetType::Text);
    }

    #[test]
    fn conversions() {
        let o = ValueOptions::default();
        assert_eq!(convert("42", TargetType::Integer, &o), Ok(Param::Int(42)));
        assert_eq!(
            convert("18446744073709551615", TargetType::Integer, &o),
            Ok(Param::Decimal("18446744073709551615".into()))
        );
        assert!(convert("4.2", TargetType::Integer, &o).is_err());
        assert_eq!(convert("", TargetType::Integer, &o), Ok(Param::Null));
        assert_eq!(
            convert(".5", TargetType::Decimal, &o),
            Ok(Param::Decimal("0.5".into()))
        );
        assert!(convert("1e5; DROP", TargetType::Decimal, &o).is_err());
        assert_eq!(
            convert("Yes", TargetType::Boolean, &o),
            Ok(Param::Bool(true))
        );
        assert_eq!(
            convert("2024-02-29", TargetType::Date, &o),
            Ok(Param::Date(19_782))
        );
        assert!(convert("2023-02-29", TargetType::Date, &o).is_err());
        assert_eq!(
            convert(
                "1970-01-01T00:00:01.5",
                TargetType::Timestamp { zoned: false },
                &o
            ),
            Ok(Param::Timestamp {
                micros: 1_500_000,
                utc: false
            })
        );
        assert_eq!(
            convert(
                "1970-01-01 02:00:00+02",
                TargetType::Timestamp { zoned: true },
                &o
            ),
            Ok(Param::Timestamp {
                micros: 0,
                utc: true
            })
        );
        assert_eq!(
            convert(
                "1970-01-01 02:00:00+02:00",
                TargetType::Timestamp { zoned: false },
                &o
            ),
            Err(ConvertError::UnexpectedOffset)
        );
        assert_eq!(
            convert("\\x00ff", TargetType::Binary, &o),
            Ok(Param::Bytes(vec![0, 255]))
        );
        let o = ValueOptions {
            null_text: Some("\\N".into()),
            empty_is_null: false,
            trim: Trim::Both,
        };
        assert_eq!(convert(" \\N ", TargetType::Text, &o), Ok(Param::Null));
        assert_eq!(
            convert("", TargetType::Text, &o),
            Ok(Param::Text(String::new()))
        );
        assert_eq!(
            convert(" a ", TargetType::Text, &o),
            Ok(Param::Text("a".into()))
        );
    }

    fn targets() -> Vec<TargetColumn> {
        vec![
            TargetColumn::new("id", "integer").with_nullable(false),
            TargetColumn::new("name", "text"),
            TargetColumn::new("born", "date"),
        ]
    }

    #[test]
    fn preview_and_mapping() {
        let csv = "Name,ID,extra,born\nann,1,x,2000-01-01\nbob,two,y,\n,,z,2000-13-01\n";
        let p = preview(
            csv.as_bytes(),
            CsvFormat::default(),
            CsvLimits::default(),
            &ValueOptions::default(),
            &targets(),
            MappingMode::ByName,
            10,
        )
        .unwrap();
        assert_eq!(p.field_count, 4);
        assert!(p.complete);
        assert_eq!(
            p.mapping.columns,
            vec![
                MappedColumn {
                    source: 0,
                    target: 1
                },
                MappedColumn {
                    source: 1,
                    target: 0
                },
                MappedColumn {
                    source: 3,
                    target: 2
                },
            ]
        );
        assert_eq!(p.guessed[3], GuessedType::Text);
        assert_eq!(p.guessed[2], GuessedType::Text);
        let described: Vec<String> = p.issues.iter().map(RowIssue::describe).collect();
        assert_eq!(
            described,
            vec![
                "line 3: column id: not a valid integer",
                "line 4: column born: not a valid date",
            ]
        );
        // No value appears in any issue or Debug output.
        let debug = format!("{p:?}");
        assert!(!debug.contains("ann") && !debug.contains("two"));
    }

    #[test]
    fn row_source_batches_and_skips() {
        let csv = "id,name,born\n1,a,2000-01-01\nx,b,\n3,c,\n,d,\n5,e\n";
        let t = targets();
        let mapping = ColumnMapping::by_position(3, &t);
        let mut src = RowSource::open(
            csv.as_bytes(),
            CsvFormat::default(),
            CsvLimits::default(),
            ValueOptions::default(),
            t,
            mapping,
        )
        .unwrap();
        let b = src.next_batch(2, usize::MAX).unwrap().unwrap();
        assert_eq!(b.lines, vec![2, 4]);
        assert_eq!(b.issues.len(), 1);
        let b = src.next_batch(10, usize::MAX).unwrap().unwrap();
        assert!(b.rows.is_empty());
        let kinds: Vec<_> = b.issues.iter().map(|i| (i.line, i.kind.clone())).collect();
        assert_eq!(
            kinds,
            vec![
                (
                    5,
                    IssueKind::NullNotAllowed {
                        column: "id".into()
                    }
                ),
                (6, IssueKind::MissingField { found: 2 }),
            ]
        );
        assert!(src.next_batch(10, usize::MAX).unwrap().is_none());
    }
}
